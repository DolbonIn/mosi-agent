#!/usr/bin/env node
/*
 * Copy EVERY glyph from apps/mobile/src/ui/Icon.tsx into kit.js (between the ICONS:BEGIN / ICONS:END markers), so
 * drafts draw exactly the app's icon set. Re-run after Icon.tsx changes:
 *
 *   node docs/design/drafts/_kit/build-icons.mjs
 *
 * It converts the JSX in `const PATHS` to SVG strings: {ring} → the 8.5 circle, {dot(x, y, r)} → filled dot,
 * d={GEAR} → the same computed gear path. Fails loudly if any other JSX expression appears.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const iconSrc = path.resolve(here, "../../../../apps/mobile/src/ui/Icon.tsx");
const kitJs = path.join(here, "kit.js");

function gearPath() {
  const teeth = 8, R = 8.7, r = 6.7, w = Math.PI / teeth;
  const f = (n) => Math.round(n * 100) / 100;
  const p = (a, rad) => `${f(12 + Math.cos(a) * rad)},${f(12 + Math.sin(a) * rad)}`;
  let d = "";
  for (let i = 0; i < teeth; i++) {
    const a = (i / teeth) * Math.PI * 2 - Math.PI / 2;
    d += `${i === 0 ? "M" : "L"}${p(a - 0.5 * w, r)}L${p(a - 0.28 * w, R)}L${p(a + 0.28 * w, R)}L${p(a + 0.5 * w, r)}`;
    d += `A${r},${r} 0 0 1 ${p(a + 1.5 * w, r)}`;
  }
  return `${d}Z`;
}

const src = fs.readFileSync(iconSrc, "utf8");
const start = src.indexOf("const PATHS");
const end = src.indexOf("\n};", start);
if (start < 0 || end < 0) throw new Error("const PATHS not found in Icon.tsx");
const body = src.slice(src.indexOf("{", start) + 1, end);

const entries = [];
for (const line of body.split("\n")) {
  const m = line.match(/^  ("[^"]+"|[A-Za-z0-9_]+): ?(.*)$/);
  if (m) entries.push({ name: m[1].replace(/"/g, ""), text: m[2] });
  else if (entries.length) entries[entries.length - 1].text += `\n${line}`;
}

const out = {};
for (const { name, text } of entries) {
  let t = text.trim().replace(/,\s*$/, "").trim();
  if (t.startsWith("(") && t.endsWith(")")) t = t.slice(1, -1);
  t = t
    .replace(/<>|<\/>/g, "")
    .replace(/\{ring\}/g, '<circle cx="12" cy="12" r="8.5"/>')
    .replace(/\{dot\(([^)]*)\)\}/g, (_, a) => {
      const [cx, cy, r = "1.35"] = a.split(",").map((s) => s.trim());
      return `<circle cx="${cx}" cy="${cy}" r="${r}" fill="currentColor" stroke="none"/>`;
    })
    .replace(/d=\{GEAR\}/g, `d="${gearPath()}"`)
    .replace(/\s*\/>/g, "/>")
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .trim();
  if (/[{}]/.test(t)) throw new Error(`unconverted JSX in icon "${name}": ${t.slice(0, 120)}`);
  if (/[a-z][A-Z]\w*=/.test(t)) throw new Error(`camelCase attribute in icon "${name}": ${t.slice(0, 120)}`);
  out[name] = t;
}

const block = `/* ICONS:BEGIN generated by build-icons.mjs from apps/mobile/src/ui/Icon.tsx (${Object.keys(out).length} glyphs), do not edit */
  const PATHS = ${JSON.stringify(out, null, 4).replace(/\n}/, "\n  }")};
  /* ICONS:END */`;
const kit = fs.readFileSync(kitJs, "utf8");
const b = kit.indexOf("/* ICONS:BEGIN");
const e = kit.indexOf("/* ICONS:END */");
if (b < 0 || e < 0) throw new Error("ICONS markers not found in kit.js");
fs.writeFileSync(kitJs, kit.slice(0, b) + block + kit.slice(e + "/* ICONS:END */".length));
console.log(`kit.js ← ${Object.keys(out).length} glyphs: ${Object.keys(out).join(", ")}`);
